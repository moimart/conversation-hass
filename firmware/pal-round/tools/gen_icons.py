#!/usr/bin/env python3
"""Generate the icon table shared by the server and the firmware.

    gen_icons.py <materialdesignicons.css>

Writes ../../../server/app/device_icons.py (name -> codepoint), ../main/icons.h
(C defines) and icons_range.txt (the codepoint list)."""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
css = open(sys.argv[1], encoding="utf-8").read()
cps = {m.group(1): int(m.group(2), 16)
       for m in re.finditer(r'\.mdi-([a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9A-Fa-f]+)"', css)}
names = [l.strip() for l in open(os.path.join(here, "icon_names.txt")) if l.strip() and not l.startswith("#")]
missing = [n for n in names if n not in cps]
if missing:
    sys.exit(f"unknown icons: {missing}")
names = list(dict.fromkeys(names))
out = os.path.join(here, "..", "..", "..", "server", "app", "device_icons.py")
with open(out, "w") as f:
    f.write('"""Material Design Icons the PAL Round firmware can draw (name -> codepoint).\n\n'
            'GENERATED by firmware/pal-round/tools/gen_icons.py from icon_names.txt —\n'
            'edit the list there and regenerate (the firmware font must match)."""\n\n'
            "MDI = {\n")
    for n in names:
        f.write(f'    "{n}": 0x{cps[n]:05X},\n')
    f.write("}\n")
with open(os.path.join(here, "..", "main", "icons.h"), "w") as f:
    f.write("// GENERATED by tools/gen_icons.py from tools/icon_names.txt — do not edit.\n"
            "// Material Design Icons codepoints available in the embedded font.\n#pragma once\n\n")
    for n in names:
        f.write(f"#define ICON_{n.upper().replace('-', '_')} 0x{cps[n]:05X}\n")
with open(os.path.join(here, "icons_range.txt"), "w") as f:
    f.write(",".join(f"0x{cps[n]:X}" for n in names))
print(f"{len(names)} icons")
